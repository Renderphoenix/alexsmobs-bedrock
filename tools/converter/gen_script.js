// Writes BP/scripts/main.js: multipart chains, follower heads, bucket catching, egg block hatching, item abilities.
'use strict';
const fs = require('fs');
const path = require('path');
const C = require('./config');

function generateScript(ctx) {
  const cfg = { CHAINS: ctx.chains, FOLLOWERS: ctx.followers, BUCKETS: ctx.buckets, EGGS: ctx.eggs, AB: ctx.abilities };
  const src = `// Alex's Mobs 2 - generated by tools/converter/gen_script.js (do not edit by hand)
import { world, system, ItemStack } from "@minecraft/server";

const NS = "${C.NS}";
const CHAINS = ${JSON.stringify(cfg.CHAINS)};
const FOLLOWERS = ${JSON.stringify(cfg.FOLLOWERS)};
const BUCKETS = ${JSON.stringify(cfg.BUCKETS)};
const EGGS = ${JSON.stringify(cfg.EGGS)};
const RAY = ${JSON.stringify(cfg.AB.ray)};
const SCAN = ${JSON.stringify(cfg.AB.scan)};
const SOUND = ${JSON.stringify(cfg.AB.sound)};
const FOOD = ${JSON.stringify(cfg.AB.food)};
const PART_TYPES = new Set([...Object.values(CHAINS).map((c) => c.part), ...Object.values(FOLLOWERS).map((f) => f.part)]);

const valid = (e) => { try { return !!e && (typeof e.isValid === "function" ? e.isValid() : e.isValid); } catch { return false; } };
const prop = (e, k, d = 0) => { try { const v = e.getProperty(k); return v === undefined ? d : v; } catch { return d; } };
const setProp = (e, k, v) => { try { e.setProperty(k, v); } catch {} };

// ------------------------------------------------------------ multipart chains
const live = new Map(); // head id -> { head, parts: Entity[], pos: Vec3[] }

function linkChain(head) {
  if (!valid(head) || live.has(head.id)) return;
  const cfg = CHAINS[head.typeId];
  if (!cfg) return;
  const dim = head.dimension;
  let parts = [];
  try {
    parts = dim.getEntities({ type: cfg.part, location: head.location, maxDistance: 64 })
      .filter((p) => p.getDynamicProperty("am:head") === head.id)
      .sort((a, b) => prop(a, NS + ":index") - prop(b, NS + ":index"));
  } catch {}
  if (parts.length !== cfg.count) {
    for (const p of parts) try { p.remove(); } catch {}
    parts = [];
    const skin = cfg.skin ? (head.getComponent("minecraft:variant")?.value ?? 0) : 0;
    for (let i = 0; i < cfg.count; i++) {
      try {
        const p = dim.spawnEntity(cfg.part, head.location);
        setProp(p, NS + ":seg", cfg.segs[i]);
        setProp(p, NS + ":index", i);
        if (cfg.skin) setProp(p, NS + ":skin", skin);
        p.setDynamicProperty("am:head", head.id);
        parts.push(p);
      } catch {}
    }
  }
  live.set(head.id, { head, parts, cfg, follower: false });
}

function linkFollower(body) {
  if (!valid(body) || live.has(body.id)) return;
  const cfg = FOLLOWERS[body.typeId];
  if (!cfg) return;
  let part;
  try { part = body.dimension.getEntities({ type: cfg.part, location: body.location, maxDistance: 32 }).find((p) => p.getDynamicProperty("am:head") === body.id); } catch {}
  if (!part) {
    try { part = body.dimension.spawnEntity(cfg.part, body.location); part.setDynamicProperty("am:head", body.id); } catch { return; }
  }
  live.set(body.id, { head: body, parts: [part], cfg, follower: true });
}

function forward(rot) {
  const yaw = (rot.y * Math.PI) / 180;
  return { x: -Math.sin(yaw), y: 0, z: Math.cos(yaw) };
}

function tickChains() {
  for (const [id, c] of live) {
    const head = c.head;
    if (!valid(head)) {
      for (const p of c.parts) if (valid(p)) try { p.remove(); } catch {}
      live.delete(id);
      continue;
    }
    let hl;
    try { hl = head.location; } catch { continue; }
    if (c.follower) {
      const p = c.parts[0];
      if (!valid(p)) { live.delete(id); continue; }
      const f = forward(head.getRotation());
      const [ox, oy, oz] = c.cfg.offset;
      const pos = { x: hl.x + f.x * -oz + ox, y: hl.y + oy, z: hl.z + f.z * -oz };
      try { p.teleport(pos, { facingLocation: { x: pos.x + f.x * 4, y: pos.y, z: pos.z + f.z * 4 } }); } catch {}
      continue;
    }
    let prev = hl;
    const sp = c.cfg.spacing;
    for (let i = 0; i < c.parts.length; i++) {
      const p = c.parts[i];
      if (!valid(p)) continue;
      let pl;
      try { pl = p.location; } catch { continue; }
      const dx = pl.x - prev.x, dy = pl.y - prev.y, dz = pl.z - prev.z;
      const d = Math.sqrt(dx * dx + dy * dy + dz * dz) || 1;
      const k = sp / d;
      const pos = d > sp ? { x: prev.x + dx * k, y: prev.y + dy * k, z: prev.z + dz * k } : pl;
      try { p.teleport(pos, { facingLocation: prev }); } catch {}
      prev = pos;
    }
  }
}

function scan() {
  for (const dimId of ["overworld", "nether", "the_end"]) {
    let dim;
    try { dim = world.getDimension(dimId); } catch { continue; }
    for (const type of Object.keys(CHAINS)) try { for (const e of dim.getEntities({ type })) linkChain(e); } catch {}
    for (const type of Object.keys(FOLLOWERS)) try { for (const e of dim.getEntities({ type })) linkFollower(e); } catch {}
    // orphaned parts (head unloaded or gone)
    for (const type of PART_TYPES) try {
      for (const p of dim.getEntities({ type })) {
        const hid = p.getDynamicProperty("am:head");
        const c = hid && live.get(hid);
        if (!c || !c.parts.some((x) => x.id === p.id)) p.remove();
      }
    } catch {}
  }
}

world.afterEvents.entitySpawn.subscribe(({ entity }) => {
  if (!entity) return;
  const t = entity.typeId;
  if (CHAINS[t]) system.runTimeout(() => linkChain(entity), 2);
  else if (FOLLOWERS[t]) system.runTimeout(() => linkFollower(entity), 2);
});

// hits on a segment hurt the creature it belongs to
world.afterEvents.entityHurt.subscribe(({ hurtEntity, damage, damageSource }) => {
  if (!hurtEntity || !PART_TYPES.has(hurtEntity.typeId)) return;
  try { hurtEntity.getComponent("minecraft:health")?.resetToMaxValue(); } catch {}
  const head = world.getEntity(hurtEntity.getDynamicProperty("am:head"));
  if (!valid(head) || damage <= 0) return;
  try {
    const opts = { cause: damageSource.cause };
    if (damageSource.damagingEntity && damageSource.damagingEntity.id !== head.id) opts.damagingEntity = damageSource.damagingEntity;
    head.applyDamage(damage, opts);
  } catch {}
});

world.afterEvents.entityDie.subscribe(({ deadEntity }) => {
  const c = deadEntity && live.get(deadEntity.id);
  if (!c) return;
  for (const p of c.parts) if (valid(p)) try { p.kill(); } catch {}
  live.delete(deadEntity.id);
});

// ------------------------------------------------------------ buckets: water bucket on a bucketable creature
world.afterEvents.playerInteractWithEntity.subscribe((ev) => {
  const { player, target } = ev;
  const held = ev.beforeItemStack ?? ev.itemStack;
  const bucket = target && BUCKETS[target.typeId];
  if (!bucket || !held || held.typeId !== "minecraft:water_bucket") return;
  system.run(() => {
    try {
      const inv = player.getComponent("minecraft:inventory").container;
      inv.setItem(player.selectedSlotIndex, new ItemStack(bucket, 1));
      target.remove();
    } catch {}
  });
});

// ------------------------------------------------------------ helpers
const snd = (dim, id, loc) => {
  try { dim.playSound(id, loc); return; } catch {}
  try { dim.runCommand("playsound " + id + " @a " + loc.x + " " + loc.y + " " + loc.z); } catch {}
};
const nice = (t) => t.split(":")[1].replace(/_/g, " ");

// ------------------------------------------------------------ egg blocks: crack stage 0..2, then hatch (like the turtle egg)
const HATCH = NS + ":hatch";
system.beforeEvents.startup.subscribe(({ blockComponentRegistry }) => {
  blockComponentRegistry.registerCustomComponent(NS + ":egg", {
    onTick(ev) {
      try {
        const block = ev.block;
        const mob = EGGS[block.typeId];
        if (!mob || Math.random() > 0.45) return;
        const dim = ev.dimension;
        const stage = block.permutation.getState(HATCH) ?? 0;
        if (stage < 2) {
          block.setPermutation(block.permutation.withState(HATCH, stage + 1));
          snd(dim, "block.turtle_egg.crack", block.center());
          return;
        }
        snd(dim, "block.turtle_egg.break", block.center());
        block.setType("minecraft:air");
        const n = Math.random() < 0.35 ? 2 : 1;
        for (let i = 0; i < n; i++) {
          const baby = dim.spawnEntity(mob, block.bottomCenter());
          try { baby.triggerEvent("minecraft:entity_born"); } catch {}
        }
      } catch (e) { console.warn("[alexsmobs] egg hatch failed: " + e); }
    },
    onStepOn(ev) {
      try {
        const who = ev.entity;
        if (!who || (who.typeId === "minecraft:player" && who.isSneaking) || Math.random() > 0.05) return;
        snd(ev.dimension, "block.turtle_egg.break", ev.block.center());
        ev.block.setType("minecraft:air");
      } catch {}
    },
  });
});

// ------------------------------------------------------------ item abilities
const wearDown = (player, slot) => {
  try {
    const inv = player.getComponent("minecraft:inventory").container;
    const item = inv.getItem(slot);
    const dur = item && item.getComponent("minecraft:durability");
    if (!dur) return;
    dur.damage = Math.min(dur.maxDurability, dur.damage + 1);
    inv.setItem(slot, dur.damage >= dur.maxDurability ? undefined : item);
  } catch {}
};
const startCooldown = (player, item) => {
  try { item.getComponent("minecraft:cooldown")?.startCooldown(player); } catch {}
};
const compass = (dx, dz) => {
  const a = (Math.atan2(dx, -dz) * 180) / Math.PI;
  return ["north", "north-east", "east", "south-east", "south", "south-west", "west", "north-west"][((Math.round(a / 45) % 8) + 8) % 8];
};

world.afterEvents.itemUse.subscribe(({ source: player, itemStack: item }) => {
  if (!player || !item) return;
  const id = item.typeId;
  try {
    const ray = RAY[id];
    if (ray) {
      const hits = player.getEntitiesFromViewDirection({ maxDistance: ray.range }) || [];
      const slot = player.selectedSlotIndex;
      for (const h of hits.slice(0, 3)) {
        const t = h.entity;
        if (!valid(t) || t.id === player.id) continue;
        for (const [eff, sec, amp] of ray.effects) { try { t.addEffect(eff, sec * 20, { amplifier: amp }); } catch {} }
        if (ray.damage) { try { t.applyDamage(ray.damage, { cause: "entityAttack", damagingEntity: player }); } catch {} }
        if (ray.pull) {
          const dx = player.location.x - t.location.x, dz = player.location.z - t.location.z;
          const len = Math.sqrt(dx * dx + dz * dz) || 1;
          try { t.applyImpulse({ x: (dx / len) * ray.pull, y: 0.35, z: (dz / len) * ray.pull }); } catch {}
        }
      }
      if (ray.sound) snd(player.dimension, ray.sound, player.location);
      if (ray.durability) wearDown(player, slot);
      startCooldown(player, item);
      return;
    }
    const sc = SCAN[id];
    if (sc) {
      const found = player.dimension.getEntities({ location: player.location, maxDistance: sc.radius })
        .filter((e) => e.id !== player.id && (sc.types ? sc.types.includes(e.typeId) : e.typeId.startsWith(NS + ":") && !PART_TYPES.has(e.typeId) && !e.typeId.endsWith("_projectile")));
      if (!found.length) { player.onScreenDisplay.setActionBar("\u00a7e" + sc.label + ": \u00a7fnothing within " + sc.radius + " blocks"); }
      else {
        found.sort((a, b) => dist(player.location, a.location) - dist(player.location, b.location));
        const n = found[0];
        const d = Math.round(dist(player.location, n.location));
        player.onScreenDisplay.setActionBar("\u00a7e" + sc.label + ": \u00a7f" + found.length + " nearby. Nearest: " + nice(n.typeId) + ", " + d + " blocks " + compass(n.location.x - player.location.x, n.location.z - player.location.z));
      }
      snd(player.dimension, "random.orb", player.location);
      return;
    }
    const so = SOUND[id];
    if (so) { snd(player.dimension, so.sound, player.location); startCooldown(player, item); }
  } catch (e) { console.warn("[alexsmobs] item use failed: " + e); }
});
const dist = (a, b) => Math.sqrt((a.x - b.x) ** 2 + (a.y - b.y) ** 2 + (a.z - b.z) ** 2);

// food effects after eating
world.afterEvents.itemCompleteUse.subscribe(({ source, itemStack }) => {
  const list = itemStack && FOOD[itemStack.typeId];
  if (!list || !source) return;
  for (const [eff, sec, amp] of list) { try { source.addEffect(eff, sec * 20, { amplifier: amp }); } catch {} }
});

system.runInterval(tickChains, 1);
system.runInterval(scan, 100);
system.runTimeout(scan, 40);
`;
  const out = path.join(C.BP, 'scripts', 'main.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, src);
}

module.exports = { generateScript };
